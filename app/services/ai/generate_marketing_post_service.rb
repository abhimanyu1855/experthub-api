# frozen_string_literal: true

module Ai
  class GenerateMarketingPostService
    def self.generate_post(booking:)
      summary_record = booking.session_summary
      return nil unless summary_record

      summary_text = summary_record.summary
      api_key = ENV["ANTHROPIC_API_KEY"]

      system_prompt = <<~SYSTEM
        You are a world-class marketing copywriter specializing in personal branding for elite professional consultants.
        Your task is to take the summary of a consultation session and write a highly engaging, professional LinkedIn post that highlights the expert's thought leadership and insights.
        
        Rules:
        1. Keep client details entirely confidential. Use generic terms like "a client in fintech" or "a growing medical clinic".
        2. Focus on the core problem solved, the frameworks discussed, and key educational takeaways.
        3. The tone must be authoritative, prestigious, and status-enhancing. Use clean spacing, bold hook sentences, and a professional call-to-action.
        4. Do not mention that this was generated by an AI assistant or formatted from a transcript summary.
      SYSTEM

      if api_key.blank? || api_key == "sk-ant-xxx"
        # Mock LinkedIn post for development/test
        return <<~POST
          🚀 Just wrapped up an advisory session with a growth-stage startup navigating scale challenges. 

          We dove deep into unit economics, client onboarding flow bottlenecks, and optimizing payment conversions. 

          Key takeaway: If you aren't looking at your transaction drop-off rates, you're leaving revenue on the table. Focus on building trust at the checkout step.

          Looking forward to seeing their progress! #ExecutiveAdvisory #Consulting #Startups #Growth
        POST
      end

      # Construct request to Claude
      conn = Faraday.new(url: "https://api.anthropic.com") do |f|
        f.request :json
        f.response :json
        f.adapter Faraday.default_adapter
      end

      response = conn.post("/v1/messages") do |req|
        req.headers["x-api-key"] = api_key
        req.headers["anthropic-version"] = "2023-06-01"
        req.body = {
          model: "claude-3-5-sonnet-20241022",
          max_tokens: 1000,
          system: system_prompt,
          messages: [
            { role: "user", content: "Write a LinkedIn post based on this session summary:\n\n#{summary_text}" }
          ]
        }
      end

      if response.success?
        response.body.dig("content", 0, "text").to_s.strip
      else
        Rails.logger.error "Anthropic Marketing Post API error: #{response.status} - #{response.body}"
        nil
      end
    end
  end
end
